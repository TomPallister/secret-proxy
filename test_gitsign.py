"""Proxy-held git signing: SSHSIG output, payload policy and the addon route.

Every key here is generated by the test; no vault is read.
"""
import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.asymmetric.rsa import generate_private_key
from mitmproxy import http

import addon
import gitsign
from secretstore import SecretManifest

COMMIT = (
    b"tree 4b825dc642cb6eb9a060e54bf8d69288fbee4904\n"
    b"author Developer <developer@example.com> 1700000000 +0000\n"
    b"committer Developer <developer@example.com> 1700000000 +0000\n"
    b"\nfeat: signed by the proxy\n"
)
TAG = (
    b"object 4b825dc642cb6eb9a060e54bf8d69288fbee4904\n"
    b"type commit\ntag v1.0.0\n"
    b"tagger Developer <developer@example.com> 1700000000 +0000\n\nv1.0.0\n"
)


def openssh_private(key) -> str:
    return key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.OpenSSH,
        serialization.NoEncryption(),
    ).decode("ascii")


def openssh_public(key) -> str:
    return key.public_key().public_bytes(
        serialization.Encoding.OpenSSH, serialization.PublicFormat.OpenSSH
    ).decode("ascii")


class TestGitSign(unittest.TestCase):
    def setUp(self):
        self.key = Ed25519PrivateKey.generate()
        self.private = openssh_private(self.key)
        self.public = openssh_public(self.key)

    @unittest.skipUnless(shutil.which("ssh-keygen"), "ssh-keygen is not installed")
    def test_signature_verifies_with_ssh_keygen(self):
        for payload in (COMMIT, TAG):
            signature = gitsign.sign(self.private, payload, "key::" + self.public + " comment")
            with tempfile.TemporaryDirectory() as tmp:
                signers = Path(tmp, "allowed_signers")
                signers.write_text(f"developer@example.com {self.public}\n")
                sig = Path(tmp, "sig")
                sig.write_text(signature)
                result = subprocess.run(
                    ["ssh-keygen", "-Y", "verify", "-f", str(signers), "-I",
                     "developer@example.com", "-n", "git", "-s", str(sig)],
                    input=payload, capture_output=True,
                )
                self.assertEqual(result.returncode, 0, result.stderr.decode())
                # The namespace is bound into the signature.
                other = subprocess.run(
                    ["ssh-keygen", "-Y", "verify", "-f", str(signers), "-I",
                     "developer@example.com", "-n", "file", "-s", str(sig)],
                    input=payload, capture_output=True,
                )
                self.assertNotEqual(other.returncode, 0)

    def test_only_commit_and_tag_objects_are_signed(self):
        for payload in (b"", b"hello", b"tree nothex\n", b"ssh-auth challenge",
                        b"certificate version 0.1\npusher x\n"):
            with self.assertRaises(gitsign.GitSignError):
                gitsign.sign(self.private, payload)
        self.assertEqual(gitsign.object_kind(COMMIT), "commit")
        self.assertEqual(gitsign.object_kind(TAG), "tag")

    def test_oversized_payload_is_refused(self):
        with self.assertRaises(gitsign.GitSignError):
            gitsign.sign(self.private, COMMIT + b"x" * gitsign.MAX_PAYLOAD_BYTES)

    def test_mismatched_signing_key_is_refused(self):
        other = openssh_public(Ed25519PrivateKey.generate())
        with self.assertRaisesRegex(gitsign.GitSignError, "not the key"):
            gitsign.sign(self.private, COMMIT, other)

    def test_non_ed25519_and_garbage_keys_are_refused(self):
        rsa = openssh_private(generate_private_key(public_exponent=65537, key_size=2048))
        for private in (rsa, "not a key"):
            with self.assertRaises(gitsign.GitSignError) as caught:
                gitsign.sign(private, COMMIT)
            self.assertNotIn("PRIVATE KEY", str(caught.exception))


class TestGitSigningRoute(unittest.TestCase):
    @staticmethod
    def flow(method, path, body=b"", key=None):
        request = http.Request.make(method, "https://" + addon.SENTINEL_HOST + path, content=body)
        if key:
            request.headers[addon.GIT_SIGNING_KEY_HEADER] = key
        flow = http.HTTPFlow(None, None)
        flow.request = request
        return flow

    def generation(self, profile, value):
        manifest = SecretManifest.load(
            Path(addon.__file__).parent / "examples" / "manifest.json",
        )
        reads = self.reads

        class Resolver:
            def get(self, name):
                reads.append(name)
                if isinstance(value, Exception):
                    raise value
                return value

        return addon._StoreGeneration(manifest, Resolver(), addon._ProviderState())

    def setUp(self):
        self.reads = []
        self.key = Ed25519PrivateKey.generate()
        self.private = openssh_private(self.key)
        self.public = openssh_public(self.key)

    def run_flow(self, generation, flow):
        with patch.object(addon, "_capture_generation", return_value=generation):
            addon.request(flow)
        return flow

    def test_callers_sign_commits(self):
        for profile in ("caller-a", "caller-b"):
            flow = self.run_flow(self.generation(profile, self.private),
                                 self.flow("POST", "/git/sign", COMMIT, "key::" + self.public))
            self.assertEqual(flow.response.status_code, 200, flow.response.content)
            body = flow.response.content.decode()
            self.assertTrue(body.startswith("-----BEGIN SSH SIGNATURE-----\n"))
            self.assertNotIn("PRIVATE KEY", body)
        self.assertEqual(self.reads, ["GIT_SIGNING_SSH_KEY", "GIT_SIGNING_SSH_KEY"])

    def test_refuses_arbitrary_data_before_reading_the_key(self):
        flow = self.run_flow(self.generation("work", self.private),
                             self.flow("POST", "/git/sign", b"please sign this"))
        self.assertEqual(flow.response.status_code, 400)
        self.assertEqual(self.reads, [])

    def test_only_post_is_allowed(self):
        flow = self.run_flow(self.generation("work", self.private), self.flow("GET", "/git/sign"))
        self.assertEqual(flow.response.status_code, 405)
        self.assertEqual(self.reads, [])

    def test_mismatched_key_is_refused_without_leaking_the_key(self):
        other = openssh_public(Ed25519PrivateKey.generate())
        flow = self.run_flow(self.generation("work", self.private),
                             self.flow("POST", "/git/sign", COMMIT, other))
        self.assertEqual(flow.response.status_code, 400)
        self.assertNotIn(b"PRIVATE", flow.response.content)

    def test_provider_failure_is_reported_without_detail(self):
        flow = self.run_flow(self.generation("work", RuntimeError("vault path detail")),
                             self.flow("POST", "/git/sign", COMMIT))
        self.assertEqual(flow.response.status_code, 502)
        self.assertNotIn(b"vault path detail", flow.response.content)

    def test_signing_key_is_never_injectable(self):
        manifest = SecretManifest.load(
            Path(addon.__file__).parent / "examples" / "manifest.json",
        )
        info = manifest.secret("GIT_SIGNING_SSH_KEY")
        self.assertTrue(info.internal_only)
        self.assertEqual(info.placements, [])
        self.assertEqual(info.value_field, "sshPrivateKey")


if __name__ == "__main__":
    unittest.main()
